import { allFacts, isIndexable } from "@/data/competitor-facts";
import { PLATFORMS_DATA } from "@/data/platforms";

// Generated so the page lists can't go stale: platform pages come from src/data/platforms.ts and the
// comparison pages from the verified dataset plus the legacy competitor list.
export const dynamic = "force-static";

const BASE = "https://www.examghost.com";

export function GET() {
    const verified = allFacts();
    const lastChecked = verified.reduce((m, f) => (f.lastChecked > m ? f.lastChecked : m), "2026-01-01");

    const platformLines = PLATFORMS_DATA.map((p) => `- [${p.name}](${BASE}/${p.slug}): ${p.kind}`).join("\n");

    const compareLines = verified
        .filter((f) => isIndexable(f))
        .map((f) => `- [${f.name} vs ExamGhost](${BASE}/${f.slug})`)
        .join("\n");

    const body = `# ExamGhost

> ExamGhost is an AI Chrome extension that answers quiz and homework questions on the page. Double-click a question (multiple choice, multi-select, dropdown or short answer) and it fills in, highlights or copies the answer, or explains it step by step. Made by FoundryOne LLC (Albuquerque, NM). Free tier: 5 solves a day, no card.

Last updated: ${lastChecked}

## Key facts

- Product: ExamGhost, a Google Chrome extension for students
- Company: FoundryOne LLC, Albuquerque, New Mexico, USA. Support: support@examghost.com
- AI: answers are generated by a Gemini-based AI model
- How to use: double-click a question to solve it; Alt+S to snip a screenshot of a graph, diagram or image question; or scan the whole page
- Solver modes (switch with Alt+1 / Alt+2 / Alt+3): quick (fills in and copies the answer, no panel), highlight (marks the correct option with a check), explain (fills in and opens a side panel with step-by-step reasoning)
- Answer delivery: auto-fill, highlight, or clipboard copy
- Reads equations and LaTeX; tuned prompts for 13 subjects
- Master on/off switch in the extension popup
- Pricing: Free (5 solves/day, no card); $19/month; $99/year (about $8.25/month); $199 lifetime; 14-day money-back guarantee
- Works on 20 named platforms (listed below) and, with an Alt+S screenshot, any page you can see. Double-click works on most quiz pages.
- Limits: free plan has 5 solves a day; paid plans have no daily limit, screenshot solves included
- Limitations: answers come from an AI model and can be wrong. Instructors may restrict AI tools on graded work; users must follow their school's academic integrity policy.

## Main pages

- [Home](${BASE}/): What ExamGhost does, how it works, and pricing
- [Features](${BASE}/features): Solver modes, screenshot snip, page scan, subjects and answer delivery
- [FAQ](${BASE}/faq): Common questions on setup, pricing, platforms and refunds
- [Pricing (Markdown)](${BASE}/pricing.md): Plan table with prices and dates
- [Compare](${BASE}/compare): Master comparison of ${verified.length} quiz and homework tools with prices from each vendor's own site (last checked ${lastChecked})
- [Free Canvas demo](${BASE}/canvas-quiz-solver-free-demo): Try the solver on a sample Canvas-style quiz in the browser
- [About](${BASE}/about): Who builds ExamGhost (FoundryOne LLC)
- [Contact](${BASE}/contact): Support and contact details
- [Privacy Policy](${BASE}/privacy): What data is collected and sent to the AI service
- [Terms of Service](${BASE}/terms): Terms of use, refunds and acceptable use
- [Full details for LLMs](${BASE}/llms-full.txt): Longer plain-text product description

## Platform pages

${platformLines}

## Optional

One-to-one comparison pages. For competitor facts and prices, see ${BASE}/compare.

${compareLines}
`;

    return new Response(body, { headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "public, max-age=3600" } });
}
